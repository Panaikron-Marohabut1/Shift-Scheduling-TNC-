/* ==========================================================================
   เครื่องมือพื้นฐานของหน้าจอ
   --------------------------------------------------------------------------
   $()   หาองค์ประกอบในหน้า
   esc() ทำให้ข้อความปลอดภัยก่อนใส่ใน HTML — ทุกค่าที่มาจากผู้ใช้หรือฐานข้อมูลต้องผ่าน esc()
   js()  ทำให้ข้อความปลอดภัยก่อนใส่เป็นค่าในคำสั่งของปุ่ม เช่น data-click="SF.cell(${js(id)})"
   ========================================================================== */

export const $ = (sel, root) => (root || document).querySelector(sel);
export const esc = v => String(v == null ? '' : v).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
export const js = v => esc(JSON.stringify(String(v))); // ค่าข้อความสำหรับใส่ในคำสั่งของปุ่ม
